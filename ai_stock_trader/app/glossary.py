def look(label: str) -> str | None:
    """화면 라벨로 설명을 찾는다. 없으면 None."""
    if not label:
        return None
    s = label.strip().strip(":").strip()
    if s in TERMS:
        return TERMS[s]
    if s in ALIASES:
        return TERMS.get(ALIASES[s])
    # 괄호 안팎을 떼고 한 번 더 (예: "연환산(CAGR)" -> "연환산")
    head = s.split("(")[0].strip()
    if head and head in TERMS:
        return TERMS[head]
    if head and head in ALIASES:
        return TERMS.get(ALIASES[head])
    # 라벨 안에 알려진 용어가 통째로 들어 있는 경우 (긴 것부터)
    for k in sorted(TERMS, key=len, reverse=True):
        if len(k) >= 3 and k in s:
            return TERMS[k]
    return None


def has(label: str) -> bool:
    return look(label) is not None
